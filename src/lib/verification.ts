import { ResumeData, CandidateVerification, InterviewQuestion } from '@/types';

/**
 * Matches declared user details with extracted resume details
 */
export function matchCandidateWithResume(
  declared: { name: string; rollNo?: string; email: string; phone: string },
  resume?: ResumeData | null
): CandidateVerification {
  if (!resume) {
    return {
      declaredRollNo: declared.rollNo || '',
      declaredName: declared.name || 'Candidate',
      declaredEmail: declared.email || '',
      declaredPhone: declared.phone || '',
      resumeName: 'N/A',
      resumeEmail: 'N/A',
      resumePhone: 'N/A',
      nameMatch: true,
      contactMatch: true,
      verificationScore: 100,
      discrepancies: []
    };
  }

  const clean = (s: string) => s.toLowerCase().replace(/[^a-z0-9]/g, '');

  const declaredNameClean = clean(declared.name);
  const resumeNameClean = clean(resume.parsed.fullName);

  const nameMatch =
    declaredNameClean.includes(resumeNameClean) ||
    resumeNameClean.includes(declaredNameClean) ||
    declared.name.toLowerCase().split(/\s+/).some((part) => part.length > 2 && resume.parsed.fullName.toLowerCase().includes(part));

  const declaredEmailClean = declared.email.toLowerCase().trim();
  const resumeEmailClean = resume.parsed.email.toLowerCase().trim();
  const emailMatch = !declaredEmailClean || !resumeEmailClean || declaredEmailClean === resumeEmailClean;

  const declaredPhoneDigits = (declared.phone || '').replace(/\D/g, '').slice(-10);
  const resumePhoneDigits = (resume.parsed.phone || '').replace(/\D/g, '').slice(-10);
  const phoneMatch = !declaredPhoneDigits || !resumePhoneDigits || declaredPhoneDigits === resumePhoneDigits;

  const discrepancies: string[] = [];
  if (!nameMatch) {
    discrepancies.push(`Declared name "${declared.name}" does not match resume name "${resume.parsed.fullName}".`);
  }
  if (!emailMatch) {
    discrepancies.push(`Declared email "${declared.email}" differs from resume contact "${resume.parsed.email}".`);
  }
  if (!phoneMatch) {
    discrepancies.push(`Declared phone "${declared.phone}" does not match resume phone "${resume.parsed.phone}".`);
  }

  let score = 100;
  if (!nameMatch) score -= 40;
  if (!emailMatch) score -= 30;
  if (!phoneMatch) score -= 20;

  return {
    declaredRollNo: declared.rollNo || '',
    declaredName: declared.name,
    declaredEmail: declared.email,
    declaredPhone: declared.phone,
    resumeName: resume.parsed.fullName,
    resumeEmail: resume.parsed.email,
    resumePhone: resume.parsed.phone,
    nameMatch,
    contactMatch: emailMatch && phoneMatch,
    verificationScore: Math.max(10, score),
    discrepancies
  };
}

/**
 * Builds the structured question sequence:
 * 1. Self-Introduction
 * 2. Resume-based questions (Certifications, Projects, Skills, Experiences)
 * 3. JD / Role-based questions (Autogenerated or manual recruiter questions)
 */
export function buildStructuredQuestionPipeline(options: {
  candidateName: string;
  targetRole: string;
  resume?: ResumeData | null;
  campaignQuestions?: InterviewQuestion[];
}): InterviewQuestion[] {
  const result: InterviewQuestion[] = [];
  let qNum = 1;

  // 1. SELF-INTRODUCTION QUESTION
  result.push({
    id: `pipeline-q-intro-${Date.now()}`,
    questionNumber: qNum++,
    category: 'HR',
    difficulty: 'Beginner',
    questionText: `Hello ${options.candidateName || 'Candidate'}. Please introduce yourself, summarize your professional background, and describe what motivated you to apply for the ${options.targetRole} position.`,
    expectedConcepts: ['Self-Introduction', 'Career Background', 'Core Strengths', 'Role Motivation'],
    rubric: {
      technicalCorrectness: 'Clear communication of technical background',
      relevance: 'Directly introduces self and aligns with target role',
      reasoning: 'Logical career progression narrative',
      communication: 'Professional confidence and articulation'
    },
    modelAnswerHint: 'Highlight your academic and professional path, primary technical competencies, and excitement for this role.'
  });

  // 2. RESUME-BASED QUESTIONS (Projects, Skills, Experiences, Certifications)
  if (options.resume) {
    const p = options.resume.parsed;

    // Project question
    if (p.projects && p.projects.length > 0) {
      const proj = p.projects[0];
      result.push({
        id: `pipeline-q-proj-${Date.now()}`,
        questionNumber: qNum++,
        category: 'Resume-Project',
        difficulty: 'Intermediate',
        questionText: `In your resume, you highlighted the project "${proj.name}". Can you walk me through your technical architecture, the role of ${proj.technologies.slice(0, 3).join(', ')}, and the key challenges you resolved?`,
        sourceResumeEvidence: `Project: ${proj.name}`,
        expectedConcepts: [...proj.technologies, 'Architecture', 'Trade-offs', 'Problem Resolution'],
        rubric: {
          technicalCorrectness: 'Accuracy in describing project stack and components',
          relevance: 'Specific alignment with claimed resume contributions',
          reasoning: 'Explains technical trade-offs evaluated during development',
          communication: 'Structured storytelling using STAR format'
        },
        modelAnswerHint: 'Detail the problem solved, tech stack choices, architectural bottlenecks, and quantitative outcomes.'
      });
    }

    // Skills & Experience / Certifications question
    if (p.skills && p.skills.length > 0) {
      const topSkills = p.skills.slice(0, 3).join(', ');
      const certMention = p.certifications && p.certifications.length > 0 ? ` and your certification in "${p.certifications[0]}"` : '';
      result.push({
        id: `pipeline-q-skills-${Date.now()}`,
        questionNumber: qNum++,
        category: 'Technical',
        difficulty: 'Intermediate',
        questionText: `Your resume lists proficiency in ${topSkills}${certMention}. Can you discuss a complex scenario where you applied these competencies to deliver a high-performance or robust solution?`,
        sourceResumeEvidence: `Skills: ${topSkills}${certMention}`,
        expectedConcepts: [topSkills, 'Performance', 'Reliability', 'Best Practices'],
        rubric: {
          technicalCorrectness: 'Accurate technical command of claimed tools',
          relevance: 'Grounded in actual practical experience',
          reasoning: 'Justifies choices with engineering logic',
          communication: 'Crisp technical vocabulary'
        },
        modelAnswerHint: 'Give a concrete technical walkthrough demonstrating hands-on mastery.'
      });
    }
  }

  // 3. JD-RELATED QUESTIONS (from campaign or role bank)
  if (options.campaignQuestions && options.campaignQuestions.length > 0) {
    for (const cq of options.campaignQuestions) {
      result.push({
        ...cq,
        id: `pipeline-q-jd-${qNum}`,
        questionNumber: qNum++
      });
    }
  } else {
    // Default JD question
    result.push({
      id: `pipeline-q-jd-${Date.now()}`,
      questionNumber: qNum++,
      category: 'Problem-Solving',
      difficulty: 'Advanced',
      questionText: `For this ${options.targetRole} role, how would you design a scalable, fault-tolerant system architecture that satisfies high-throughput operational requirements?`,
      expectedConcepts: ['Scalability', 'Fault Tolerance', 'Modularity', 'Error Handling', 'Monitoring'],
      rubric: {
        technicalCorrectness: 'Architectural sound principles and design patterns',
        relevance: 'Directly addresses production scalability',
        reasoning: 'Weighs trade-offs between consistency, availability, and latency',
        communication: 'Structured architectural presentation'
      },
      modelAnswerHint: 'Decompose the architecture into tiers, discuss caching, data persistence, and failure recovery.'
    });
  }

  return result;
}
